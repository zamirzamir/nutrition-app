#!/usr/bin/env bash
# Ночная пересборка СУПЕР-ПРЕСЕТОВ на исправленных данных (15.07).
# Запуск из корня nutrition-app:  bash пересборка_пресетов.sh
# Идёт несколько часов — то, что нужно на ночь. Текущий anchors_seeds.json НЕ трогается
# (билдер пишет в anchors_seeds_SUPER.json), так что риска потерять рабочие пресеты нет.
set -e
cd "$(dirname "$0")"
TS=$(date +%Y%m%d_%H%M)

echo "▶ 1/3 Бэкап текущих пресетов…"
mkdir -p _АРХИВ
cp anchors_seeds.json "_АРХИВ/anchors_seeds_beforeRebuild_${TS}.json"
echo "  ✓ _АРХИВ/anchors_seeds_beforeRebuild_${TS}.json"

echo "▶ 2/3 Чищу старые чекпоинты seeds_super/…"
echo "  (ОБЯЗАТЕЛЬНО: иначе билдер пропустит якоря, собранные ЕЩЁ БЕЗ запрета дублей в дне)"
rm -rf seeds_super
echo "  ✓ seeds_super удалён — соберёт всё заново по новым правилам"

echo "▶ 3/3 Запуск билдера (120 сек/якорь × 238 ≈ 8 часов). Пишет в anchors_seeds_SUPER.json…"
echo "  Можно прерывать (Ctrl+C) и запускать снова — продолжит с места (чекпоинты)."
python3 build_super_presets.py 120

echo ""
echo "✅ Сборка завершена. УТРОМ пошагово:"
echo "   1) Открой  super_presets_report.md  — там вердикт по каждому якорю (✅/❌) и сравнение с текущими."
echo "   2) Проверка безопасности:  python3 validate_presets.py"
echo "      (ждём ~60 маргинальных превышений UL: B3 36/35, B9 ~1010/1000, Fe ~36/36 — это НОРМА"
echo "       на честных микро-данных, старые пресеты стояли на заниженных. Билдер держит 80%-зазор.)"
echo "   3) Если вердикт ок:  cp anchors_seeds_SUPER.json anchors_seeds.json"
echo "   4) Залей на сайт:    bash app-v2/deploy-v2.sh"
echo "   5) Проверь в кабинете пару дней меню (свайп → плашка «в норме»)."
echo ""
echo "Если что-то не так — ничего не потеряно: текущие пресеты в бэкапе выше, просто не делай шаг 3."
